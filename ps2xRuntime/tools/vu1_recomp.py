#!/usr/bin/env python3
"""Compile VU1 code images to C++ (see ps2xRuntime/include/runtime/ps2_vu1_compiled.h).

usage: vu1_recomp.py <out_dir> <vu1_image.bin>...

Images come from a run with PS2X_VU1_DUMP=<dir> (vu1_<hash>.bin). Each becomes
<out_dir>/vu1_<hash>.cpp, which registers itself; at run time it is used whenever VU1 code
memory holds the same words, and the interpreter runs everything else.
"""
import os
import struct
import sys

UPPER_SPECIAL_OK = set(range(0x00, 0x2B)) | {0x2C, 0x2D, 0x2E, 0x2F, 0x30}
LOWER_HI_OK = {0x00, 0x01, 0x04, 0x05, 0x08, 0x09, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18,
               0x1A, 0x1B, 0x1C, 0x20, 0x21, 0x24, 0x25, 0x28, 0x29, 0x2C, 0x2D, 0x2E, 0x2F}
LOWER_DIRECT_OK = {0x30, 0x31, 0x32, 0x34, 0x35}
LOWER_SPECIAL_OK = ({0x30, 0x31} | set(range(0x34, 0x44)) | {0x64, 0x68, 0x69, 0x6C} | set(range(0x70, 0x7E)))
FLAG_READERS = {0x14, 0x16, 0x17, 0x18, 0x1A, 0x1B}  # FSEQ FSAND FSOR FMEQ FMAND FMOR


def special(w):
    return (w & 3) | ((w >> 4) & 0x7C)


def upper_ok(u):
    op = u & 0x3F
    if op <= 0x2F:
        return True
    return op >= 0x3C and special(u) in UPPER_SPECIAL_OK


def lower_ok(l):
    if l in (0, 0x8000033C):
        return True
    hi = (l >> 25) & 0x7F
    if hi in LOWER_HI_OK:
        return True
    if hi != 0x40:
        return False
    if (l & 0x3F) < 0x3C:
        return (l & 0x3F) in LOWER_DIRECT_OK
    return special(l) in LOWER_SPECIAL_OK


def branch_kind(u, l):
    """None, ('static', target) or ('dynamic',)."""
    if u & 0x80000000:
        return None
    hi = (l >> 25) & 0x7F
    if hi in (0x24, 0x25):
        return ('dynamic',)
    if hi in (0x20, 0x21) or 0x28 <= hi <= 0x2F:
        imm = l & 0x7FF
        if imm & 0x400:
            imm -= 0x800
        return ('static', imm)
    return None


def compile_image(path, out_dir):
    code = open(path, 'rb').read()
    name = os.path.basename(path)[:-4]
    pairs = [struct.unpack_from('<II', code, pc) for pc in range(0, len(code), 8)]  # (lower, upper)
    end = max(i for i, p in enumerate(pairs) if p != (0, 0)) + 1
    flags = any(not (u & 0x80000000) and ((l >> 25) & 0x7F) in FLAG_READERS for l, u in pairs[:end])
    if any(u & 0x18000000 for l, u in pairs[:end]):
        print(f'{name}: uses D/T halt bits, skipped')
        return None

    out = [f'// Generated by vu1_recomp.py from {os.path.basename(path)}. Do not edit.',
           '#include "runtime/ps2_vu1_compiled.h"', '', 'using namespace vu1c;', '', 'namespace {',
           'const uint32_t kCode[] = {']
    words = [w for l, u in pairs[:end] for w in (l, u)]
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join(f'0x{w:08X}u' for w in words[i:i + 8]) + ',')
    out += ['};', '', 'bool run(Ctx &c)', '{', 'dispatch:', '    switch (c.pc)', '    {']
    out += [f'    case 0x{i * 8:04X}: goto L{i * 8:04X};' for i in range(end)]
    out += ['    default: return false;', '    }']
    F = 'true' if flags else 'false'
    for i in range(end):
        pc = i * 8
        l, u = pairs[i]
        prev = pairs[i - 1] if i else None
        prev_branch = branch_kind(prev[1], prev[0]) if prev else None
        out.append(f'L{pc:04X}:')
        if not (upper_ok(u) and (u & 0x80000000 or lower_ok(l))) or (prev_branch and branch_kind(u, l)):
            out.append(f'    c.pc = 0x{pc:04X}; return false; // not compiled')
            continue
        out.append(f'    P<0x{u:08X}u, 0x{l:08X}u, 0x{pc:04X}, {F}>(c);')
        if prev and prev[1] & 0x40000000:  # this is the E-bit delay slot
            out.append(f'    if (c.eb) {{ c.pc = c.br ? c.target : 0x{(pc + 8) & 0x3FFF:04X}; c.br = c.eb = false; goto done; }}')
        if u & 0x40000000:
            out.append('    c.eb = true;')
        if prev_branch:
            if prev_branch[0] == 'dynamic':
                out.append('    if (c.br) { c.br = false; c.pc = c.target; goto dispatch; }')
            else:
                target = (pc + prev_branch[1] * 8) & 0x3FFF  # relative to the branch's pc + 8
                if target < end * 8:
                    guard = f'if (c.cyc > (1u << 28)) {{ c.pc = 0x{target:04X}; return false; }} ' if target <= pc else ''
                    out.append(f'    if (c.br) {{ c.br = false; {guard}goto L{target:04X}; }}')
                else:
                    out.append(f'    if (c.br) {{ c.br = false; c.pc = 0x{target:04X}; return false; }}')
    out += [f'    c.pc = 0x{end * 8:04X};', '    return false;', 'done:', '    flushAll(c);', '    return true;', '}', '',
            f'const Program kProgram{{"{name}", kCode, sizeof(kCode), &run, {F}}};',
            'struct Register', '{', '    Register() { registerProgram(&kProgram); }', '} registerIt;', '}', '']
    dst = os.path.join(out_dir, name + '.cpp')
    with open(dst, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print(f'{name}: {end} pairs, flags={"yes" if flags else "no"} -> {dst}')
    return dst


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    os.makedirs(sys.argv[1], exist_ok=True)
    for path in sys.argv[2:]:
        compile_image(path, sys.argv[1])


if __name__ == '__main__':
    main()
